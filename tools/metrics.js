#!/usr/bin/env node
// Full backtest metrics for TRU POWER vs the Statbotics EPA re-implementation, all seasons.
//   node tools/metrics.js <data-dir> <results-dir> [out-dir]
// Reads <results-dir>/tru-<year>.json and epa-<year>.json (written by tools/reproduce.sh) and
// the matches in <data-dir>/<year>/matches. Writes BACKTEST.md (tables) and
// predictions-<year>.csv (one row per match) to out-dir (default: docs/backtest).
//
// Definitions (decided official-event qualification matches only; ties excluded):
//   accuracy       share of matches where the favoured alliance (p > 0.5) won
//   Brier          mean (p − y)², y = 1 if red won. 0 is perfect, 1 is worst possible;
//                  always predicting 50% scores exactly 0.25
//   Brier skill    1 − Brier / 0.25: improvement over always predicting 50%
//   log loss       mean −[y ln p + (1−y) ln(1−p)], p clipped to [0.001, 0.999]
//   calibration    logistic regression y ~ a + b·logit(p): slope b = 1 and intercept a = 0 is
//                  perfect; b < 1 means over-confident, b > 1 under-confident
//   ECE            expected calibration error over 10 equal-width bins: Σ (n_bin/N)·|mean p − win rate|
//   intervals      95% percentile intervals from a cluster bootstrap that resamples whole events
//                  (2,000 resamples, fixed seed), because matches at one event share teams
'use strict';
const fs = require('fs');
const path = require('path');
const LA = require('../js/linalg.js');

const [dataDir, resDir, outDir = 'docs/backtest'] = process.argv.slice(2);
if (!resDir) { console.error('usage: metrics.js <data-dir> <results-dir> [out-dir]'); process.exit(1); }
const YEARS = [2026, 2025, 2024];
const B = 2000;
fs.mkdirSync(outDir, { recursive: true });

const clip = p => Math.min(0.999, Math.max(0.001, p));
const logit = p => Math.log(clip(p) / (1 - clip(p)));

// Logistic recalibration y ~ a + b·logit(p) by Newton's method.
function calib(ps, ys) {
  let a = 0, b = 1;
  for (let it = 0; it < 50; it++) {
    let g0 = 0, g1 = 0, h00 = 0, h01 = 0, h11 = 0;
    for (let i = 0; i < ps.length; i++) {
      const x = logit(ps[i]), q = 1 / (1 + Math.exp(-(a + b * x))), w = q * (1 - q);
      g0 += ys[i] - q; g1 += (ys[i] - q) * x; h00 += w; h01 += w * x; h11 += w * x * x;
    }
    const det = h00 * h11 - h01 * h01;
    const da = (h11 * g0 - h01 * g1) / det, db = (h00 * g1 - h01 * g0) / det;
    a += da; b += db;
    if (Math.abs(da) + Math.abs(db) < 1e-10) break;
  }
  return { a, b };
}
function ece(ps, ys) {
  const bins = Array.from({ length: 10 }, () => ({ n: 0, p: 0, y: 0 }));
  ps.forEach((p, i) => { const k = Math.min(9, Math.floor(p * 10)); bins[k].n++; bins[k].p += p; bins[k].y += ys[i]; });
  return bins.reduce((s, b) => s + (b.n ? b.n / ps.length * Math.abs(b.p / b.n - b.y / b.n) : 0), 0);
}
function basic(rows, key) {
  let c = 0, br = 0, ll = 0;
  for (const r of rows) { const p = r[key]; c += (p > 0.5) === (r.y === 1) ? 1 : 0; br += (p - r.y) ** 2; ll -= r.y ? Math.log(clip(p)) : Math.log(1 - clip(p)); }
  return { acc: c / rows.length, brier: br / rows.length, ll: ll / rows.length };
}
const q = (arr, p) => { const a = arr.slice().sort((x, y) => x - y); return a[Math.floor(p * (a.length - 1))]; };
const f = (x, d = 4) => (x >= 0 ? '' : '−') + Math.abs(x).toFixed(d);
const pc = (x, d = 1) => (100 * x).toFixed(d) + '%';
const ci = (lo, hi, d = 4, mult = 1) => `${f(lo * mult, d)} to ${f(hi * mult, d)}`;

const out = [];
const csvAll = [];
out.push('# TRU POWER three-season backtest\n');
out.push('Generated by `node tools/metrics.js` from the output of `tools/reproduce.sh`. Every number below is computed by that script; see the definitions in its header.\n');
out.push('Scope: official-event qualification matches with a winner (ties excluded). Each match is predicted using only matches played before it; season priors use only events that finished before the event started. **2026 is the season the settings were tuned on; 2025 and 2024 are blind tests with frozen settings.** The comparison model is a re-implementation of Statbotics EPA from its open-source code (its API was unavailable).\n');

const summary = [], diffs = [], calRows = [], phaseRows = [];
for (const Y of YEARS) {
  const tru = JSON.parse(fs.readFileSync(path.join(resDir, `tru-${Y}.json`), 'utf8'));
  const epa = JSON.parse(fs.readFileSync(path.join(resDir, `epa-${Y}.json`), 'utf8'));
  const mdir = path.join(dataDir, String(Y), 'matches');
  const rows = [];
  for (const file of fs.readdirSync(mdir)) {
    let raw; try { raw = JSON.parse(fs.readFileSync(path.join(mdir, file), 'utf8')); } catch (e) { continue; }
    if (!Array.isArray(raw)) continue;
    const quals = raw.filter(m => m.comp_level === 'qm' && m.alliances.red.score >= 0).sort((a, b) => a.match_number - b.match_number);
    quals.forEach((m, i) => {
      const al = m.alliances;
      if (al.red.score === al.blue.score || tru[m.key] == null || epa[m.key] == null) return;
      rows.push({ key: m.key, ev: m.event_key, y: al.red.score > al.blue.score ? 1 : 0, tru: tru[m.key], epa: epa[m.key], phase: i < quals.length / 3 ? 0 : i < 2 * quals.length / 3 ? 1 : 2 });
    });
  }
  rows.sort((a, b) => (a.key < b.key ? -1 : 1));
  for (const r of rows) csvAll.push(`${Y},${r.ev},${r.key},${r.y},${r.tru.toFixed(5)},${r.epa.toFixed(5)}`);
  const evs = [...new Set(rows.map(r => r.ev))];
  const byEv = Object.fromEntries(evs.map(e => [e, rows.filter(r => r.ev === e)]));
  const T = basic(rows, 'tru'), E = basic(rows, 'epa');
  // Cluster bootstrap over events.
  const rng = LA.makeRng(Y);
  const bs = { accT: [], brT: [], dAcc: [], dBr: [], dLl: [], ph: [[], [], []] };
  for (let b = 0; b < B; b++) {
    const s = [];
    for (let i = 0; i < evs.length; i++) for (const r of byEv[evs[Math.floor(rng.uniform() * evs.length)]]) s.push(r);
    const t = basic(s, 'tru'), e = basic(s, 'epa');
    bs.accT.push(t.acc); bs.brT.push(t.brier); bs.dAcc.push(t.acc - e.acc); bs.dBr.push(e.brier - t.brier); bs.dLl.push(e.ll - t.ll);
    for (let ph = 0; ph < 3; ph++) { const pr = s.filter(r => r.phase === ph); bs.ph[ph].push(basic(pr, 'epa').brier - basic(pr, 'tru').brier); }
  }
  const better = evs.filter(e => basic(byEv[e], 'tru').brier < basic(byEv[e], 'epa').brier).length;
  summary.push(`| ${Y}${Y === 2026 ? ' (tuned)' : ' (blind)'} | ${evs.length} | ${rows.length.toLocaleString('en')} | ${pc(T.acc)} (${pc(q(bs.accT, .025))}–${pc(q(bs.accT, .975))}) | ${pc(E.acc)} | ${T.brier.toFixed(4)} | ${E.brier.toFixed(4)} | ${pc(1 - T.brier / 0.25)} | ${pc(1 - E.brier / 0.25)} | ${T.ll.toFixed(4)} | ${E.ll.toFixed(4)} |`);
  const dB = E.brier - T.brier, dA = T.acc - E.acc, dL = E.ll - T.ll;
  const verdict = q(bs.dBr, .025) > 0 ? 'TRU POWER lower (better)' : q(bs.dBr, .975) < 0 ? 'EPA lower (better)' : 'not distinguishable';
  diffs.push(`| ${Y} | ${f(100 * dA, 2)} pts (${ci(q(bs.dAcc, .025), q(bs.dAcc, .975), 2, 100)}) | ${f(dB)} (${ci(q(bs.dBr, .025), q(bs.dBr, .975))}) | ${f(dL)} (${ci(q(bs.dLl, .025), q(bs.dLl, .975))}) | ${better}/${evs.length} | ${verdict} |`);
  for (const [name, key] of [['TRU POWER', 'tru'], ['EPA', 'epa']]) {
    const c = calib(rows.map(r => r[key]), rows.map(r => r.y));
    calRows.push(`| ${Y} | ${name} | ${c.b.toFixed(3)} | ${f(c.a, 3)} | ${pc(ece(rows.map(r => r[key]), rows.map(r => r.y)))} |`);
  }
  for (let ph = 0; ph < 3; ph++) {
    const pr = rows.filter(r => r.phase === ph), t = basic(pr, 'tru'), e = basic(pr, 'epa');
    const lo = q(bs.ph[ph], .025), hi = q(bs.ph[ph], .975);
    phaseRows.push(`| ${Y} | ${['First third', 'Middle third', 'Last third'][ph]} | ${pr.length.toLocaleString('en')} | ${pc(t.acc)} | ${pc(e.acc)} | ${t.brier.toFixed(4)} | ${e.brier.toFixed(4)} | ${f(e.brier - t.brier)} (${ci(lo, hi)}) | ${lo > 0 ? 'TRU POWER' : hi < 0 ? 'EPA' : 'neither'} |`);
  }
}
out.push('## Overall\n');
out.push('Accuracy interval: 95% cluster-bootstrap interval over events. Brier skill = 1 − Brier / 0.25 (improvement over always predicting 50%). Lower Brier and log loss are better.\n');
out.push('| Season | Events | Matches | TRU POWER accuracy (95% CI) | EPA accuracy | TRU POWER Brier | EPA Brier | TRU POWER Brier skill | EPA Brier skill | TRU POWER log loss | EPA log loss |');
out.push('|---|---|---|---|---|---|---|---|---|---|---|');
out.push(...summary, '');
out.push('## Paired differences (TRU POWER vs EPA, same matches)\n');
out.push('Positive = TRU POWER better. 95% intervals from 2,000 cluster-bootstrap resamples of events. "Not distinguishable" means the interval includes zero.\n');
out.push('| Season | Accuracy difference | Brier difference | Log-loss difference | Events where TRU POWER has lower Brier | Brier verdict |');
out.push('|---|---|---|---|---|---|');
out.push(...diffs, '');
out.push('## Calibration\n');
out.push('Logistic recalibration y ~ a + b·logit(p). Perfect calibration: slope 1, intercept 0. Slope above 1 = predictions are too cautious; below 1 = too confident. ECE = expected calibration error over 10 equal-width bins.\n');
out.push('| Season | Model | Slope | Intercept | ECE |');
out.push('|---|---|---|---|---|');
out.push(...calRows, '');
out.push('## By event phase\n');
out.push('Matches split by position in each event\'s qualification schedule.\n');
out.push('| Season | Phase | Matches | TRU POWER accuracy | EPA accuracy | TRU POWER Brier | EPA Brier | Brier difference (95% CI; + = TRU POWER better) | Better (CI excludes 0) |');
out.push('|---|---|---|---|---|---|---|---|---|');
out.push(...phaseRows, '');
out.push('## Per-match predictions\n');
out.push('`predictions-all.csv` lists every match used above: season, event, match key, outcome (1 = red won), TRU POWER\'s red-win probability, and EPA\'s. Any figure on this page can be recomputed from it.\n');
fs.writeFileSync(path.join(outDir, 'BACKTEST.md'), out.join('\n'));
fs.writeFileSync(path.join(outDir, 'predictions-all.csv'), 'season,event,match,red_won,p_tru_power,p_epa\n' + csvAll.join('\n') + '\n');
console.log(out.join('\n'));
